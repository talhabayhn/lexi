plugins {
    id("lexi.jvm.application")
    alias(libs.plugins.sqldelight)
}

dependencies {
    implementation(project(":core:domain"))
    implementation(libs.sqldelight.sqlite.driver)
    implementation(libs.kotlinx.serialization.json)
}

sqldelight {
    databases {
        // Generated from core:data's content.db schema (single source of truth) plus the compiler-only
        // INSERT statements in src/main/sqldelight. No project dependency on core:data (ARCHITECTURE.md §2).
        create("ContentDatabase") {
            packageName.set("dev.talhabayhan.lexi.tools.contentcompiler.db")
            srcDirs(
                rootProject.file("core/data/src/commonMain/sqldelight-content"),
                file("src/main/sqldelight"),
            )
        }
    }
}

application {
    mainClass.set("dev.talhabayhan.lexi.tools.contentcompiler.MainKt")
}

// `./gradlew :tools:content-compiler:run` resolves the default paths (content/, build/content/) from the repo root.
tasks.named<JavaExec>("run") {
    workingDir = rootDir
}

// content.db for the app, generated by every build (docs/CONTENT.md §1). The output directory is laid out as a
// Compose resources directory (`files/content.db` + `files/content-version.txt`); `shared` consumes it through the
// `contentDbElements` variant below, so nothing in the app depends on this tool's code.
val contentDbDir: Provider<Directory> = layout.buildDirectory.dir("generated/content-db")

val generateContentDb by tasks.registering(JavaExec::class) {
    group = "build"
    description = "Validates content/ (+ \$LEXI_PACKS_DIR) and writes content.db as a Compose resource for shared."
    classpath = sourceSets.main.get().runtimeClasspath
    mainClass.set(application.mainClass)
    workingDir = rootDir

    // Locals only: lambdas below must not capture the script object (configuration cache).
    val root = rootDir
    val contentDir = rootProject.layout.projectDirectory.dir("content").asFile
    val outputDir = contentDbDir
    val tempDir = layout.buildDirectory.dir("content-compiler")
    val packsDir = providers.environmentVariable("LEXI_PACKS_DIR")

    inputs.dir(contentDir).withPathSensitivity(PathSensitivity.RELATIVE).withPropertyName("content")
    inputs.property("packsDir", packsDir.orElse(""))
    inputs.files(packsDir.map { listOf(File(it).takeIf(File::isAbsolute) ?: File(root, it)) }.orElse(emptyList()))
        .withPathSensitivity(PathSensitivity.RELATIVE)
        .withPropertyName("packs")
        .optional()
    inputs.property("sourceDateEpoch", providers.environmentVariable("SOURCE_DATE_EPOCH").orElse(""))
    outputs.dir(outputDir).withPropertyName("contentDb")

    argumentProviders.add(
        CommandLineArgumentProvider {
            val files = outputDir.get().dir("files").asFile
            listOf(
                "--content",
                contentDir.path,
                "--out",
                files.resolve("content.db").path,
                "--version-file",
                files.resolve("content-version.txt").path,
                "--tmp",
                tempDir.get().asFile.path,
            )
        },
    )
}

configurations.consumable("contentDbElements") {
    attributes.attribute(Usage.USAGE_ATTRIBUTE, objects.named(Usage::class.java, "lexi-content-db"))
    outgoing.artifact(contentDbDir) {
        type = "directory"
        builtBy(generateContentDb)
    }
}
