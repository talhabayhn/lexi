import java.util.Properties

plugins {
    // this is necessary to avoid the plugins to be loaded multiple times
    // in each subproject's classloader
    alias(libs.plugins.androidApplication) apply false
    alias(libs.plugins.androidMultiplatformLibrary) apply false
    alias(libs.plugins.composeMultiplatform) apply false
    alias(libs.plugins.composeCompiler) apply false
    alias(libs.plugins.kotlinMultiplatform) apply false
    alias(libs.plugins.kotlinJvm) apply false
    alias(libs.plugins.kotlinSerialization) apply false
    alias(libs.plugins.sqldelight) apply false
    alias(libs.plugins.roborazzi) apply false
    alias(libs.plugins.ktlint) apply false
    alias(libs.plugins.googleServices) apply false
    alias(libs.plugins.firebaseCrashlytics) apply false
}

// Root lifecycle tasks so `./gradlew build` also runs the build-logic unit tests (module rules).
plugins.apply("base")
tasks.named("check") {
    dependsOn(gradle.includedBuild("build-logic").task(":convention:check"))
}

// One app version for both stores: gradle.properties is the source, Version.xcconfig is the committed copy Xcode reads.
// Values are captured as plain strings so the tasks stay configuration-cache compatible.
val versionProps = Properties().apply { file("gradle.properties").inputStream().use { load(it) } }
val lexiVersionName: String = versionProps.getProperty("lexi.versionName").trim()
val lexiVersionCode: String = versionProps.getProperty("lexi.versionCode").trim()
val iosVersionFile: File = file("iosApp/Configuration/Version.xcconfig")
val iosVersionContent: String =
    "// Generated by ./gradlew syncIosVersion from gradle.properties; do not edit by hand.\n" +
        "MARKETING_VERSION=$lexiVersionName\nCURRENT_PROJECT_VERSION=$lexiVersionCode\n"

tasks.register("syncIosVersion") {
    group = "versioning"
    description = "Writes iosApp/Configuration/Version.xcconfig from gradle.properties."
    val target = iosVersionFile
    val content = iosVersionContent
    doLast { target.writeText(content) }
}

val checkIosVersionSync = tasks.register("checkIosVersionSync") {
    group = "versioning"
    description = "Fails when versionCode breaks the formula or Version.xcconfig is out of sync with gradle.properties."
    val name = lexiVersionName
    val code = lexiVersionCode
    val target = iosVersionFile
    val content = iosVersionContent
    doLast {
        val m = Regex("""(\d+)\.(\d+)\.(\d+)""").matchEntire(name)
            ?: throw GradleException("lexi.versionName '$name' is not x.y.z")
        val (major, minor, patch) = m.destructured
        val expected = major.toInt() * 10000 + minor.toInt() * 100 + patch.toInt()
        if (code != expected.toString()) {
            throw GradleException(
                "lexi.versionCode=$code but lexi.versionName=$name requires $expected " +
                    "(major*10000 + minor*100 + patch). Use scripts/bump-version.sh.",
            )
        }
        if (!target.exists() || target.readText() != content) {
            throw GradleException("${target.name} is out of sync with gradle.properties. Run ./gradlew syncIosVersion.")
        }
    }
}
tasks.named("check") { dependsOn(checkIosVersionSync) }
