package dev.talhabayhan.lexi.core.platform.feedback

import dev.talhabayhan.lexi.core.domain.feedback.HapticKind
import dev.talhabayhan.lexi.core.domain.feedback.Haptics
import dev.talhabayhan.lexi.core.domain.feedback.SoundEffect
import dev.talhabayhan.lexi.core.domain.feedback.SoundPlayer

/** [Haptics] that does nothing while the "Titreşim" setting is off. */
public class GatedHaptics(private val delegate: Haptics, private val enabled: () -> Boolean) : Haptics {
    override fun perform(kind: HapticKind) {
        if (enabled()) delegate.perform(kind)
    }
}

/** [SoundPlayer] that does nothing while the "Ses efektleri" setting is off. */
public class GatedSoundPlayer(private val delegate: SoundPlayer, private val enabled: () -> Boolean) :
    SoundPlayer,
    AutoCloseable {
    override fun play(effect: SoundEffect) {
        if (enabled()) delegate.play(effect)
    }

    /** Releases the delegate's resources when it holds any. */
    override fun close() {
        (delegate as? AutoCloseable)?.close()
    }
}

/** File name (without extension) of the effect's asset. */
public val SoundEffect.assetName: String
    get() = name.lowercase()

/** Compose resource path of the effect's WAV asset (generated by `tools/sounds/generate_sounds.py`). */
public val SoundEffect.assetPath: String
    get() = "files/sounds/$assetName.wav"
